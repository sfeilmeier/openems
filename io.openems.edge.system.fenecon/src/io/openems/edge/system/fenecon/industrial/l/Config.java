package io.openems.edge.system.fenecon.industrial.l;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

import io.openems.edge.common.startstop.StartStopConfig;
import io.openems.edge.system.fenecon.industrial.l.envicool.Envicool;

@ObjectClassDefinition(//
		name = "System FENECON Industrial L", //
		description = "Implements the FENECON Industrial L core component")
public @interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "system0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Start/stop behaviour?", description = "Should this Component be forced to start or stop?")
	StartStopConfig startStop() default StartStopConfig.AUTO;

	@AttributeDefinition(name = "Ess-ID", description = "ID of Ess device.")
	String ess_id();

	@AttributeDefinition(name = "Battery IDs", description = "IDs of battery devices.")
	String[] battery_ids();

	@AttributeDefinition(name = "CoolingUnit: Enabled?", description = "Start or stop the CoolingUnit")
	Envicool.Mode coolingUnitMode() default Envicool.Mode.ENABLED;

	@AttributeDefinition(name = "CoolingUnit: Modbus-ID", description = "ID of Modbus bridge of the CoolingUnit.")
	String coolingUnitModbus_id();

	@AttributeDefinition(name = "CoolingUnit: Modbus Unit-ID", description = "The Unit-ID of the Modbus device of the CoolingUnit.")
	int coolingUnitModbusUnitId() default 1;

	@AttributeDefinition(name = "CoolingUnit: Cooling Temperature", description = "The Cooling temperature in Celsius. Must be between 10 °C and 35 °C")
	int coolingUnitCoolingSetPoint();

	@AttributeDefinition(name = "CoolingUnit: Heating Temperature", description = "The Heating temperature in Celsius. Must be between 10 °C and 35 °C")
	int coolingUnitHeatingSetPoint();

	@AttributeDefinition(name = "Smoke detection installed", description = "is smoke detection installed?")
	boolean isSmokeDetectionInstalled() default false;

	@AttributeDefinition(name = "Ess target filter", description = "This is auto-generated by 'Ess-ID'.")
	String ess_target() default "(enabled=true)";

	@AttributeDefinition(name = "Battery target filter", description = "This is auto-generated by 'Battery-ID'.")
	String Battery_target() default "(enabled=true)";

	@AttributeDefinition(name = "Cooling unit modbus target filter", description = "This is auto-generated by 'CoolingUnitModbus-ID'.")
	String CoolingUnitModbus_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "System FENECON Industrial L [{id}]";

}